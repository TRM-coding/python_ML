def add_and_assign(a, b):
    a += b
    return a


def subtract_and_assign(a, b):
    a -= b
    return a


def multiply_and_assign(a, b):
    a *= b
    return a


def divide_and_assign(a, b):
    a /= b
    return a


def floor_divide_and_assign(a, b):
    a //= b
    return a


def modulo_and_assign(a, b):
    a %= b
    return a


def power_and_assign(a, b):
    a **= b
    return a


def bitwise_and_assign(a, b):
    a &= b
    return a


def bitwise_or_assign(a, b):
    a |= b
    return a


def bitwise_xor_assign(a, b):
    a ^= b
    return a


def left_shift_and_assign(a, n):
    a <<= n
    return a


def right_shift_and_assign(a, n):
    a >>= n
    return a
