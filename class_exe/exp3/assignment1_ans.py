def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def true_divide(a, b):
    return a / b


def floor_divide(a, b):
    return a // b


def modulo(a, b):
    return a % b


def power(a, b):
    return a ** b


def negate(x):
    return -x


def positive(x):
    return +x


def absolute(x):
    return abs(x)


def divmod_pair(a, b):
    return divmod(a, b)
