"""
练习主题：比较运算符（答案版）
"""

def is_equal(a, b):
    return a == b


def is_not_equal(a, b):
    return a != b


def is_greater(a, b):
    return a > b


def is_less(a, b):
    return a < b


def is_greater_equal(a, b):
    return a >= b


def is_less_equal(a, b):
    return a <= b


def is_same_object(x, y):
    return x is y


def is_not_same_object(x, y):
    return x is not y
